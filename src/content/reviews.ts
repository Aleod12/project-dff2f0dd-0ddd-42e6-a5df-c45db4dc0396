/** Name (with age if set), or the fallback label when the name is empty. */
export const reviewTitle = (r: VideoReview) => {
  if (!r.name.trim()) return r.fallbackLabel;
  return r.age?.trim() ? `${r.name}, ${r.age}` : r.name;
};
