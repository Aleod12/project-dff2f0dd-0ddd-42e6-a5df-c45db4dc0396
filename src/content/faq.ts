export const answerText = (a: Part[]) => a.map((p) => p.text).join("");

/** FAQPage structured data, built from the same items. */
export function faqJsonLd() {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faq.items.map((i) => ({
      "@type": "Question",
      name: i.q,
      acceptedAnswer: { "@type": "Answer", text: answerText(i.a) },
    })),
  };
}
